#[cfg(test)]
mod tests {
    use super::*;

    fn placeholders(s: &str) -> Vec<String> {
        let mut found: Vec<String> = (0..10)
            .map(|i| format!("{{{i}}}"))
            .filter(|p| s.contains(p.as_str()))
            .collect();
        found.sort();
        found
    }

    #[test]
    fn every_language_has_every_key_with_the_same_placeholders() {
        assert_eq!(KEYS.len(), TABLE.len());
        for (index, key) in KEYS.iter().enumerate() {
            assert_eq!(*key as usize, index);
            let expected = placeholders(TABLE[index][Lang::ZhTw.index()]);
            for lang in LANGS {
                let s = TABLE[index][lang.index()];
                assert!(!s.trim().is_empty(), "{key:?} missing in {}", lang.code());
                assert_eq!(placeholders(s), expected, "{key:?} in {}", lang.code());
            }
        }
    }

    #[test]
    fn languages_round_trip_and_windows_tags_map() {
        for lang in LANGS {
            assert_eq!(Lang::from_code(lang.code()), Some(lang));
            assert_eq!(Lang::from_tag(lang.code()), Some(lang));
        }
        assert_eq!(Lang::from_tag("zh-Hant-TW"), Some(Lang::ZhTw));
        assert_eq!(Lang::from_tag("zh-HK"), Some(Lang::ZhTw));
        assert_eq!(Lang::from_tag("zh-Hans-CN"), Some(Lang::ZhCn));
        assert_eq!(Lang::from_tag("pt-PT"), Some(Lang::PtBr));
        assert_eq!(Lang::from_tag("en-GB"), Some(Lang::En));
        assert_eq!(Lang::from_tag("nl-NL"), None);
    }

    #[test]
    fn fill_orders_values_per_language_and_keeps_unknown_braces() {
        let n = 3;
        assert_eq!(fill("{1} of {0}", &[&"a", &n]), "3 of a");
        assert_eq!(fill("{x} {9} {0}", &[&"v"]), "{x} {9} v");
        assert_eq!(fill("【{0}】", &[&"中文"]), "【中文】");
    }

    #[test]
    fn history_labels_follow_the_current_language() {
        assert_eq!(relabel("unknown"), "unknown");
        let label = text(K::LabelPin, Lang::Ja);
        assert_eq!(relabel(label), t(K::LabelPin));
        assert!(all(K::CatPictures).any(|s| s == "圖片"));
        assert!(all(K::CatPictures).any(|s| s == "Pictures"));
    }
}
