impl Lang {
    /// BCP 47 name, also the DirectWrite and NLS locale name.
    pub fn code(self) -> &'static str {
        match self {
            Lang::ZhTw => "zh-TW",
            Lang::ZhCn => "zh-CN",
            Lang::En => "en-US",
            Lang::Ja => "ja-JP",
            Lang::Ko => "ko-KR",
            Lang::De => "de-DE",
            Lang::Fr => "fr-FR",
            Lang::Es => "es-ES",
            Lang::PtBr => "pt-BR",
            Lang::Ru => "ru-RU",
            Lang::Vi => "vi-VN",
            Lang::Th => "th-TH",
        }
    }

    /// The language's name in itself, for the language menu.
    pub fn native(self) -> &'static str {
        match self {
            Lang::ZhTw => "繁體中文",
            Lang::ZhCn => "简体中文",
            Lang::En => "English",
            Lang::Ja => "日本語",
            Lang::Ko => "한국어",
            Lang::De => "Deutsch",
            Lang::Fr => "Français",
            Lang::Es => "Español",
            Lang::PtBr => "Português (Brasil)",
            Lang::Ru => "Русский",
            Lang::Vi => "Tiếng Việt",
            Lang::Th => "ไทย",
        }
    }

    pub fn from_code(code: &str) -> Option<Lang> {
        LANGS
            .into_iter()
            .find(|lang| lang.code().eq_ignore_ascii_case(code))
    }

    /// Maps a Windows language tag ("zh-Hant-TW", "pt-PT", "en-GB") to the
    /// closest supported language.
    pub fn from_tag(tag: &str) -> Option<Lang> {
        let tag = tag.to_ascii_lowercase();
        let primary = tag.split('-').next().unwrap_or_default();
        Some(match primary {
            "zh" => {
                if ["-tw", "-hk", "-mo", "-hant"]
                    .iter()
                    .any(|t| tag.contains(t))
                {
                    Lang::ZhTw
                } else {
                    Lang::ZhCn
                }
            }
            "en" => Lang::En,
            "ja" => Lang::Ja,
            "ko" => Lang::Ko,
            "de" => Lang::De,
            "fr" => Lang::Fr,
            "es" => Lang::Es,
            "pt" => Lang::PtBr,
            "ru" => Lang::Ru,
            "vi" => Lang::Vi,
            "th" => Lang::Th,
            _ => return None,
        })
    }

    fn index(self) -> usize {
        self as usize
    }
}

/// u8::MAX: follow Windows.
static CHOSEN: AtomicU8 = AtomicU8::new(u8::MAX);

/// The first supported language in the user's Windows display languages.
pub fn system() -> Lang {
    // Tests compare against the Traditional Chinese strings, whatever the
    // language of the machine running them.
    if cfg!(test) {
        return Lang::ZhTw;
    }
    static SYSTEM: OnceLock<Lang> = OnceLock::new();
    *SYSTEM.get_or_init(|| {
        use windows::Win32::Globalization::{GetUserPreferredUILanguages, MUI_LANGUAGE_NAME};
        let (mut count, mut size) = (0u32, 0u32);
        unsafe {
            if GetUserPreferredUILanguages(MUI_LANGUAGE_NAME, &mut count, None, &mut size).is_err()
                || size == 0
            {
                return Lang::En;
            }
            let mut buffer = vec![0u16; size as usize];
            if GetUserPreferredUILanguages(
                MUI_LANGUAGE_NAME,
                &mut count,
                Some(windows::core::PWSTR(buffer.as_mut_ptr())),
                &mut size,
            )
            .is_err()
            {
                return Lang::En;
            }
            String::from_utf16_lossy(&buffer)
                .split('\0')
                .find_map(Lang::from_tag)
                .unwrap_or(Lang::En)
        }
    })
}

/// None follows Windows.
pub fn set(choice: Option<Lang>) {
    CHOSEN.store(choice.map_or(u8::MAX, |l| l as u8), Ordering::Relaxed);
}

pub fn chosen() -> Option<Lang> {
    LANGS.get(CHOSEN.load(Ordering::Relaxed) as usize).copied()
}

pub fn current() -> Lang {
    chosen().unwrap_or_else(system)
}

pub fn t(key: K) -> &'static str {
    text(key, current())
}

pub fn text(key: K, lang: Lang) -> &'static str {
    let row = &TABLE[key as usize];
    [lang, Lang::En, Lang::ZhTw]
        .into_iter()
        .map(|l| row[l.index()])
        .find(|s| !s.is_empty())
        .unwrap_or_default()
}

/// Fills {0}, {1}, ... so each language can order the values itself.
pub fn tf(key: K, args: &[&dyn Display]) -> String {
    fill(t(key), args)
}

fn fill(template: &str, args: &[&dyn Display]) -> String {
    let mut out = String::with_capacity(template.len() + 16);
    let mut rest = template;
    while let Some(start) = rest.find('{') {
        out.push_str(&rest[..start]);
        let tail = &rest[start..];
        let index = tail
            .as_bytes()
            .get(1)
            .filter(|b| b.is_ascii_digit() && tail.as_bytes().get(2) == Some(&b'}'))
            .map(|b| (b - b'0') as usize);
        match index.and_then(|i| args.get(i)) {
            Some(value) => {
                out.push_str(&value.to_string());
                rest = &tail[3..];
            }
            None => {
                out.push('{');
                rest = &tail[1..];
            }
        }
    }
    out.push_str(rest);
    out
}

/// A NUL-terminated wide copy for Win32, kept for the process lifetime.
pub fn w(key: K) -> PCWSTR {
    static WIDE: OnceLock<Vec<Vec<Vec<u16>>>> = OnceLock::new();
    let table = WIDE.get_or_init(|| {
        LANGS
            .iter()
            .map(|&lang| {
                (0..TABLE.len())
                    .map(|k| text(KEYS[k], lang).encode_utf16().chain(Some(0)).collect())
                    .collect()
            })
            .collect()
    });
    PCWSTR(table[current().index()][key as usize].as_ptr())
}

/// Locale name for DirectWrite, so font fallback picks the right CJK/Thai face.
pub fn locale() -> PCWSTR {
    static WIDE: OnceLock<Vec<Vec<u16>>> = OnceLock::new();
    let names = WIDE.get_or_init(|| {
        LANGS
            .iter()
            .map(|l| l.code().encode_utf16().chain(Some(0)).collect())
            .collect()
    });
    PCWSTR(names[current().index()].as_ptr())
}

/// Every translation of a key, e.g. to recognise a category group created
/// while another language was selected.
pub fn all(key: K) -> impl Iterator<Item = &'static str> {
    LANGS.into_iter().map(move |lang| text(key, lang))
}

/// History labels are stored as text; show known ones in the current language.
pub fn relabel(label: &str) -> String {
    [
        K::LabelAuto,
        K::LabelDeleteGroup,
        K::LabelTransfer,
        K::LabelPin,
        K::LabelUngroup,
    ]
    .into_iter()
    .find(|&key| all(key).any(|s| s == label))
    .map_or_else(|| label.to_owned(), |key| t(key).to_owned())
}

/// Thousands separator for whole numbers in the current language.
pub fn group_separator() -> &'static str {
    match current() {
        Lang::De | Lang::Es | Lang::PtBr | Lang::Vi => ".",
        Lang::Fr | Lang::Ru => "\u{202F}",
        _ => ",",
    }
}

